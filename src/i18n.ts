const dicts: Record<Lang, Record<string, string>> = { en, ru, uk };
const locales: Record<Lang, string> = { en: 'en-US', ru: 'ru-RU', uk: 'uk-UA' };

let lang: Lang = 'en';

export function setLang(l: string | undefined): void {
  lang = l === 'ru' || l === 'uk' ? l : 'en';
  document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return lang;
}

export function locale(): string {
  return locales[lang];
}

/** Looks up `key` in the current language (English as fallback) and fills `{name}` placeholders. */
export function t(key: string, params: Record<string, string | number> = {}): string {
  const s = dicts[lang][key] ?? en[key as keyof typeof en] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Plural form: looks up `key.one`, `key.few`, `key.many` or `key.other` by the CLDR rule of the current language. */
export function tn(key: string, n: number, params: Record<string, string | number> = {}): string {
  const rule = new Intl.PluralRules(locale()).select(n);
  const full = `${key}.${rule}`;
  const k = full in dicts[lang] ? full : `${key}.other`;
  return t(k, { n, ...params });
}

/** Turns a backend error (`E_CODE:arg|arg`) into a message in the current language; other text passes through. */
export function errorText(e: unknown): string {
  const raw = typeof e === 'string' ? e : e instanceof Error ? e.message : String(e);
  return translateCode(raw);
}

export function translateCode(raw: string | null | undefined): string {
  if (!raw) return '';
  const m = /^(E_[A-Z_]+)(?::([\s\S]*))?$/.exec(raw);
  if (!m) return raw;
  const args = (m[2] ?? '').split('|');
  const params: Record<string, string> = {};
  args.forEach((a, i) => (params[String(i)] = a));
  const key = `err.${m[1]}`;
  return key in en ? t(key, params) : raw;
}
